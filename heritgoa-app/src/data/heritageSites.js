// ── Helper: derive source category from site_id ─────────────────────────
export function getSourceCategory(site) {
  if (site.site_id.startsWith('ASI-'))     return 'ASI Protected';
  if (site.site_id.startsWith('STATE-'))   return 'State Listed';
  if (site.site_id.startsWith('TOURISM-')) return 'Tourism Context';
  if (site.site_id.startsWith('COMM-'))    return 'Community';
  return 'Other';
}

